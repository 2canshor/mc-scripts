const {chromium}=require('/opt/node22/lib/node_modules/playwright');
const assert=(c,m)=>{if(!c){console.log('FAIL',m);process.exitCode=1}else console.log('ok',m)};
(async()=>{const b=await chromium.launch();const p=await b.newPage({viewport:{width:820,height:1180},hasTouch:true});const errs=[];
p.on('pageerror',e=>errs.push(e.message));
await p.goto('file://'+__dirname+'/MC Scripts.html');await p.waitForTimeout(300);
await p.click('#insert');
assert(await p.evaluate(()=>document.activeElement.id)==='event','new script starts at the event name');
await p.click('#insert',{force:true});await p.waitForTimeout(100);
assert((await p.textContent('.toast'))==='先填司儀姓名','tap on ＋ before an MC says why');
assert(await p.evaluate(()=>document.activeElement.matches('#mcline input:not(.upper)')),'and goes to the MC name');
await p.keyboard.type('甲同學');
const box=await p.evaluate(()=>{const r=document.querySelector('#mcline label.hit:nth-child(2)').getBoundingClientRect();return r.height});
console.log('   MC name tap height',Math.round(box));
const ids=()=>p.evaluate(()=>[...document.querySelectorAll('#rows .row')].map(r=>r.className.split(' ')[1]+':'+(r.querySelector('textarea')?r.querySelector('textarea').value:[...r.querySelectorAll('input')].map(i=>i.value).join('/'))));
await p.click('#insert');await p.click('.menu >> text=對白');await p.keyboard.type('各位早晨');
await p.click('#insert');await p.click('.menu >> text=對白');await p.keyboard.type('歡迎大家');
// two lines by the same MC? second defaults to same MC when one MC only
await p.keyboard.press('Home');await p.evaluate(()=>{const t=document.activeElement;t.setSelectionRange(0,0)});await p.keyboard.press('Backspace');
console.log('   ',JSON.stringify(await ids()));
assert(JSON.stringify(await ids())==='["line:各位早晨歡迎大家"]','Backspace at start joins with the line above (same MC)');
assert(await p.evaluate(()=>document.activeElement.selectionStart)===4,'cursor sits at the join');
await p.click('#insert');await p.click('.menu >> text=台上動作');await p.keyboard.type('校長上台');
await p.evaluate(()=>document.activeElement.setSelectionRange(0,0));await p.keyboard.press('Backspace');
assert(JSON.stringify(await ids())==='["line:各位早晨歡迎大家","cue:校長上台"]'&&await p.evaluate(()=>document.activeElement.value==='各位早晨歡迎大家'&&document.activeElement.selectionStart===8),'Backspace at start of a cue goes to the end of the line above');
await p.click('.row.cue');
await p.click('#insert');await p.click('.menu >> text=得獎名單');await p.keyboard.type('5A陳大文');await p.keyboard.press('Enter');await p.keyboard.type('陳小文');
console.log('   ',JSON.stringify(await ids()));
for(let i=0;i<3;i++) await p.keyboard.press('Backspace');
assert(await p.evaluate(()=>document.activeElement.value==='')&&true,'name cleared');
await p.keyboard.press('Backspace');
assert(await p.evaluate(()=>document.activeElement.classList.contains('upper')&&document.activeElement.value==='5A'),'Backspace in empty name goes to the class');
await p.keyboard.press('Backspace');await p.keyboard.press('Backspace');
assert(await p.evaluate(()=>document.activeElement.value===''),'class cleared');
await p.keyboard.press('Backspace');
console.log('   ',JSON.stringify(await ids()), await p.evaluate(()=>document.activeElement.value));
assert(JSON.stringify(await ids()).includes('award:5A/陳大文"')&&await p.evaluate(()=>document.activeElement.value==='陳大文'),'empty award row removed, cursor at end of row above');
await p.evaluate(()=>{const i=document.activeElement;i.setSelectionRange(0,0)});await p.keyboard.press('Backspace');await p.keyboard.press('Backspace');
assert(await p.evaluate(()=>document.activeElement.classList.contains('upper')),'at start of name, Backspace goes to class');
await p.evaluate(()=>document.activeElement.setSelectionRange(0,0));await p.keyboard.press('Backspace');
assert(await p.evaluate(()=>document.activeElement.value==='校長上台'),'at start of first award row, Backspace goes to the cue above');
// row tap focuses its text
await p.click('.row.line',{position:{x:12,y:10}});
assert(await p.evaluate(()=>document.activeElement.value==='各位早晨歡迎大家'),'tap on row margin focuses its text');
console.log('   FAB bottom with keyboard 300:',await p.evaluate(()=>{document.documentElement.style.setProperty('--kb','300px');return getComputedStyle(document.getElementById('insert')).bottom}));
console.log('errors',JSON.stringify(errs));await b.close();})();
